.set noreorder
.global _start
.org 0x00000000

_start:
    #########################################################
    # 1. 测试 MTC0 和 MFC0 (针对 EPC 寄存器, 编号 14)
    #########################################################
    lui  $1, 0x1234
    ori  $1, $1, 0x5678     # $1 = 0x12345678
    mtc0 $1, $14            # 将 $1 写入 CP0 EPC
    nop
    nop
    nop
    mfc0 $2, $14            # 从 CP0 EPC 读出到 $2
    # 检查点 A: 此时 $2 应该等于 0x12345678

    #########################################################
    # 2. 测试 SYSCALL 和 ERET
    #########################################################
    # 我们需要先初始化异常处理入口的代码
    # 注意：在真实硬件中这在BootLoader做，这里我们直接跳转过去写代码
    j    main_test_flow
    nop

    # -----------------------------------------------------
    # 0xBFC00380 是 MIPS 默认异常入口
    # 但由于仿真通常 RAM 很小，我们假设仿真环境的 ROM
    # 涵盖了 0x0 到高地址，或者我们在代码中模拟这个行为。
    # 这里我们把异常处理程序放在 0x100 处，
    # *关键*: 你需要在你的 exception 模块里把入口地址改成 0x100 
    # 或者把这些指令硬编码在你的 testbench 对应的 0xBFC00380 地址
    # 
    # 为了方便测试，假设你的 CPU 异常入口被你临时改为 0x00000050
    # -----------------------------------------------------
    .org 0x50
exception_handler:
    nop
    mfc0 $26, $14           # 读出 EPC 到 $26 (保存发生异常的PC)
    mfc0 $27, $13           # 读出 Cause 到 $27 (查看异常原因)
    
    # 为了防止死循环 (ERET 返回原指令再次触发)，我们需要修改 EPC += 4
    addiu $26, $26, 4
    mtc0  $26, $14          # 写回 EPC
    
    eret                    # 返回主程序
    nop

main_test_flow:
    # 这里的地址应该是 0x20 左右
    ori $3, $0, 0xAAAA      # 标记：准备执行 Syscall
    syscall                 # <--- 触发异常，跳转到 0x50
    nop
    # 检查点 B: 若程序能运行到这里，说明 ERET 成功返回
    ori $3, $0, 0xBBBB      # 标记：Syscall 返回成功

    #########################################################
    # 3. 测试 BREAK
    #########################################################
    ori $4, $0, 0xCCCC      # 标记：准备执行 Break
    break                   # <--- 触发异常，跳转到 0x50
    nop
    # 检查点 C: 若程序能运行到这里，说明 Break 返回成功
    ori $4, $0, 0xDDDD      # 标记：Break 返回成功

_end:
    j _end
    nop