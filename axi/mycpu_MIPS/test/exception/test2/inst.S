.set noreorder
.global _start
.org 0x00000000

_start:
    #########################################################
    # 1. 初始化通用寄存器
    #########################################################
    # 为了清晰起见，先清空或初始化一些寄存器
    ori  $1, $0, 0x1234
    sll  $1, $1, 16
    ori  $1, $1, 0x5678     # $1 = 0x12345678

    #########################################################
    # 2. 测试 MTC0 和 MFC0 (读写 CP0 EPC 寄存器)
    #########################################################
    # 将 $1 写入 CP0 EPC (Reg 14)
    mtc0 $1, $14
    nop
    nop 
    nop
    # 从 CP0 EPC 读回 $2
    # 预期: $2 变为 0x12345678
    mfc0 $2, $14  

    #########################################################
    # 3. 测试 SYSCALL 异常
    #########################################################
    # 异常入口地址在仿真中通常是 0xBFC00380 或 0x40 (取决于您的 Exception 模块配置)
    # 假设我们已经正确设置了 Exception Handler 在 0x40 处
    
    syscall                 # <--- 触发 Syscall 异常 (PC=0x20)
    nop                     # (延迟槽，通常异常会立刻跳转，这条可能被 Flush)

    # ==> 处理器应跳转到 0x40 执行异常处理Handler

    # [异常返回点 1] 
    # 从 Handler ERET 回来后，应该执行这里
    ori $3, $0, 0xAAAA      # 标记: Syscall 返回成功 ($3 = 0xAAAA)

    #########################################################
    # 4. 测试 BREAK 异常
    #########################################################
    break                   # <--- 触发 Break 异常
    nop

    # ==> 处理器应跳转到 0x40 执行异常处理Handler

    # [异常返回点 2]
    ori $4, $0, 0xBBBB      # 标记: Break 返回成功 ($4 = 0xBBBB)

    #########################################################
    # 5. 结束测试
    #########################################################
end_loop:
    j end_loop
    nop


# =========================================================
# 异常处理程序 (Exception Handler)
# 假设异常入口被映射到了指令内存的 0x40 处
# =========================================================
.org 0x40
exception_handler:
    # 1. 读取 EPC (异常发生时的 PC)
    mfc0 $26, $14
    
    # 2. 读取 Cause (异常原因) - 仅供调试观察
    mfc0 $27, $13 
    
    # 3. 修改 EPC += 4 (跳过触发异常的那条指令，防止死循环)
    addiu $26, $26, 4
    
    # 4. 写回 EPC
    mtc0 $26, $14
    
    # 5. 异常返回
    eret
    nop